"""
Map APRA's spreadsheets before writing any pipeline.

APRA publishes these files for people to read, not for machines: multi-row headers, merged
cells, blank spacer rows, footnotes sitting inside the data. Before anything can be cleaned,
we need to know what is actually in each file — which sheets, which dimensions, how many rows
of header, how far back the series runs.

This script answers that. It reads nothing into a model and changes nothing; it just looks,
prints a summary, and writes a first draft of docs/data-map.md for you to correct by hand.

Two questions decide this project, and this script shows where the data for each one lives:

    1. Are people downgrading instead of leaving?   Needs COVER TYPE and EXCESS level.
    2. Is the pool getting older?                   Needs membership by AGE BAND.

Run:  python etl/explore.py
"""

from __future__ import annotations

import re
import sys
from pathlib import Path

import pandas as pd

ROOT = Path(__file__).resolve().parent.parent
RAW = ROOT / "data" / "raw"
OUT = ROOT / "docs" / "data-map.md"
# Everything after this line in the data map is written by hand and kept on every re-run.
MARKER = "<!-- Hand-written below this line: kept when explore.py re-runs -->"

PREVIEW_ROWS = 12
PREVIEW_COLS = 8

# Words worth shouting about if they turn up in a sheet — they decide what the project can do.
FLAGS = {
    "age": ["age", "0-4", "25-29", "65-69", "age group", "age band"],
    "cover_type": ["full cover", "reduced cover", "exclusion", "policycover",
                   "type of cover"],
    "state": ["nsw", "vic", "qld", "state", "territory", "western australia"],
    # APRA names data columns in one word (ExcessAmount, ExclusionaryPolicy), so those are
    # listed too: whole-word matching would not see "excess" inside "excessamount".
    "excess": ["excess", "co-payment", "copayment", "excessamount", "excesspolicy"],
    "exclusion": ["exclusion", "exclusionary", "restricted", "exclusionarypolicy"],
}
# Whole words, plus simple plurals ("exclusions", "excesses"). A plain substring search finds
# "age" inside "average" and "coverage", and "vic" inside "service", which made the first data
# map claim things the data does not hold.
PATTERNS = {name: re.compile(r"\b(?:" + "|".join(map(re.escape, words)) + r")(?:s|es)?\b")
            for name, words in FLAGS.items()}


def describe_sheet(xl: pd.ExcelFile, sheet: str) -> dict:
    """Look at one sheet without assuming anything about its shape."""
    # header=None because we do not yet know how many header rows there are.
    df = xl.parse(sheet, header=None, nrows=200)
    if df.empty:
        return {"sheet": sheet, "rows": 0, "cols": 0, "flags": [], "header_guess": None,
                "preview": "(empty)"}

    full = xl.parse(sheet, header=None)

    # Everything in the sheet as lowercase text, so the flag words can be looked for.
    haystack = " ".join(
        str(v).lower() for v in df.head(60).to_numpy().ravel() if pd.notna(v)
    )
    haystack = haystack.replace("\u2013", "-")      # APRA writes age bands with en dashes: 25–29
    flags = [name for name, pattern in PATTERNS.items() if pattern.search(haystack)]

    # The header block is usually the first run of rows that are mostly text; data starts at
    # the first row that is mostly numbers. This is a guess, to be checked by eye.
    header_guess = None
    for i in range(min(25, len(df))):
        row = df.iloc[i]
        filled = row.notna().sum()
        if filled < 2:
            continue
        numeric = sum(isinstance(v, (int, float)) and pd.notna(v) for v in row)
        if numeric >= max(2, filled * 0.6):
            header_guess = i
            break

    preview = df.iloc[:PREVIEW_ROWS, :PREVIEW_COLS].to_string(
        max_colwidth=22, na_rep="", header=False
    )

    return {
        "sheet": sheet,
        "rows": len(full),
        "cols": full.shape[1],
        "flags": flags,
        "header_guess": header_guess,
        "preview": preview,
    }


def main() -> None:
    files = sorted(RAW.glob("*.xlsx"))
    if not files:
        sys.exit(
            f"No .xlsx files in {RAW.relative_to(ROOT)}.\n"
            "Download APRA's spreadsheets into that folder first — see docs/setup-steps.md."
        )

    lines: list[str] = [
        "# Data map",
        "",
        "Auto-generated by `etl/explore.py`. **Correct it by hand** — the header-row guesses in",
        "particular are guesses. This file is the reference the pipeline is written against.",
        "",
    ]
    found: dict[str, list[str]] = {k: [] for k in FLAGS}

    for path in files:
        print(f"\n{'=' * 78}\n{path.name}\n{'=' * 78}")
        lines += [f"## {path.name}", "", f"Size: {path.stat().st_size / 1e6:.1f} MB", ""]

        try:
            xl = pd.ExcelFile(path)
        except Exception as exc:  # noqa: BLE001
            print(f"  could not open: {exc}")
            lines += [f"Could not open: `{exc}`", ""]
            continue

        print(f"{len(xl.sheet_names)} sheets")
        lines += ["| Sheet | Rows | Cols | Header row | Contains |",
                  "| --- | --- | --- | --- | --- |"]

        for sheet in xl.sheet_names:
            try:
                info = describe_sheet(xl, sheet)
            except Exception as exc:  # noqa: BLE001
                print(f"  {sheet:<40} could not read: {exc}")
                continue

            for f in info["flags"]:
                found[f].append(f"{path.name} → {sheet}")

            flag_text = ", ".join(info["flags"]) or "—"
            print(f"  {sheet:<40} {info['rows']:>6} x {info['cols']:<4}  {flag_text}")
            lines.append(
                f"| {sheet} | {info['rows']} | {info['cols']} | "
                f"{info['header_guess']} | {flag_text} |"
            )

        lines.append("")

        # The first sheet's preview, so the file's shape is visible in the map.
        first = describe_sheet(xl, xl.sheet_names[0])
        lines += [f"First sheet (`{first['sheet']}`) looks like:", "", "```",
                  first["preview"], "```", ""]

    # ---- the two questions that decide the project -----------------------------------
    print(f"\n{'=' * 78}\nTHE TWO QUESTIONS\n{'=' * 78}")
    lines += ["## The two questions", ""]

    # A sheet answers a question only if it carries every dimension that question needs.
    for keys, label in [(("cover_type", "excess"),
                         "1. Downgrading instead of leaving? COVER TYPE and EXCESS"),
                        (("age",), "2. Is the pool getting older? Membership by AGE BAND")]:
        hits = [h for h in found[keys[0]] if all(h in found[k] for k in keys[1:])]
        if hits:
            print(f"\n{label}: FOUND in {len(hits)} sheet(s)")
            for h in hits[:15]:
                print(f"    {h}")
            lines += [f"**{label}: found** in:", ""]
            lines += [f"- `{h}`" for h in hits[:15]] + [""]
        else:
            print(f"\n{label}: NOT FOUND in any sheet")
            lines += [f"**{label}: not found** in these files. "
                      f"Either it is published elsewhere, or that part of the project changes "
                      f"— see CLAUDE.md, Open questions.", ""]

    for key in ("state", "exclusion"):
        if found[key]:
            print(f"\nAlso found — {key}: {len(found[key])} sheet(s)")
            lines += [f"Also present — **{key}**: {len(found[key])} sheet(s)", ""]

    kept = ""
    if OUT.exists() and MARKER in OUT.read_text():
        kept = OUT.read_text().split(MARKER, 1)[1]
    OUT.write_text("\n".join(lines) + "\n\n" + MARKER + (kept or "\n"))
    print(f"\nWrote {OUT.relative_to(ROOT)} — read it and correct the header-row guesses.\n")


if __name__ == "__main__":
    main()
