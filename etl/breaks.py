"""
Before any trend becomes a finding: where do APRA's series break?

    python etl/breaks.py

Prints the evidence and rewrites the generated part of docs/series-breaks.md, everything below
the marker line. The conclusions above the marker are written by hand from this evidence.

A jump is a quarter-on-quarter move of 1.5 points or more in a share of hospital policies,
about three times the typical move. Each jump is either explained (by APRA's notes or a rule
change) or treated as a break: no trend is drawn straight through it.
"""

from __future__ import annotations

from pathlib import Path

import pandas as pd

ROOT = Path(__file__).resolve().parent.parent
CLEAN = ROOT / "data" / "clean"
OUT = ROOT / "docs" / "series-breaks.md"
MARKER = "<!-- Generated by etl/breaks.py below this line; edit above it -->"
JUMP = 1.5
COVER_SERIES = {"Full cover", "Lifetime exclusions", "Reduced, no exclusions"}
EXPLAINED = {   # (quarter, series it applies to): what APRA's notes say
    ("Sep 2014", series): "APRA's notes: an insurer reclassified its policies from "
                          "non-exclusionary to exclusionary"
    for series in COVER_SERIES
}
LIFETIME_EXCLUSIONS = ["Reduced cover and some lifetime exclusions",
                       "Some lifetime exclusions but no reduced cover"]


def shares() -> pd.DataFrame:
    """Each quarter's hospital policies split by cover type and by excess, as % of the total."""
    c = pd.read_csv(CLEAN / "policies_by_cover.csv", parse_dates=["quarter_end"])
    total = c.groupby("quarter_end").policies.sum()
    cover = c.pivot_table(index="quarter_end", columns="policy_cover", values="policies",
                          aggfunc="sum").div(total, axis=0) * 100
    excess = c.pivot_table(index="quarter_end", columns="excess", values="policies",
                           aggfunc="sum").div(total, axis=0) * 100
    return pd.DataFrame({
        "Policies": total,
        "Full cover": cover["Full cover"],
        "Lifetime exclusions": cover[LIFETIME_EXCLUSIONS].sum(axis=1),
        "Reduced, no exclusions": cover["Reduced cover but no lifetime exclusions"],
        "Nil excess": excess["Nil"],
        "Excess up to 500": excess["Up to $500 single"],
        "Excess over 500": excess["Over $500 single"],
    })


def table(df: pd.DataFrame, index_name: str) -> list[str]:
    """A DataFrame as markdown table lines."""
    cols = [index_name] + list(df.columns)
    out = ["| " + " | ".join(cols) + " |", "| " + " | ".join("---" for _ in cols) + " |"]
    for idx, row in df.iterrows():
        cells = [f"{v:,.0f}" if isinstance(v, (int, float)) and abs(v) >= 1000 else
                 (f"{v:.1f}" if isinstance(v, float) else str(v)) for v in row]
        out.append("| " + " | ".join([str(idx)] + cells) + " |")
    return out


def main() -> None:
    s = shares()
    s.index = s.index.strftime("%b %Y")
    lines = ["## Evidence", "",
             "Shares are % of hospital policies, Australia-wide. Generated from the tidy tables.", ""]

    jumps = []
    for name in ["Full cover", "Lifetime exclusions", "Reduced, no exclusions", "Nil excess",
                 "Excess over 500"]:
        move = s[name].diff()
        for q, v in move[move.abs() >= JUMP].items():
            jumps.append((name, q, f"{v:+.1f}",
                          EXPLAINED.get((q, name), "not explained in APRA's notes")))
        print(f"{name:<24} typical move {move.abs().median():.2f} pts; "
              f"{int((move.abs() >= JUMP).sum())} jumps of {JUMP}+")
    lines += [f"### Jumps of {JUMP} points or more in one quarter", "",
              "| Series | Quarter | Move (points) | Explanation |", "| --- | --- | --- | --- |"]
    lines += [f"| {n} | {q} | {m} | {e} |" for n, q, m, e in jumps] + [""]

    lines += ["### Around the April 2019 reforms", ""]
    lines += table(s.loc["Mar 2018":"Dec 2020"], "Quarter") + [""]
    lines += ["### The excess series, 2007 to 2011", ""]
    lines += table(s.loc["Jun 2007":"Jun 2011", ["Nil excess", "Excess up to 500",
                                                  "Excess over 500"]], "Quarter") + [""]

    a = pd.read_csv(CLEAN / "insured_by_age.csv", parse_dates=["quarter_end"])
    p = pd.read_csv(CLEAN / "population_by_age.csv", parse_dates=["quarter_end"])
    old = []
    for q in sorted(p.quarter_end.unique()):
        ai, pi = a[a.quarter_end == q], p[p.quarter_end == q]
        ins = 100 * ai[ai.age_band_start >= 65].insured_persons.sum() / ai.insured_persons.sum()
        pop = 100 * pi[pi.age_band_start >= 65].population.sum() / pi.population.sum()
        old.append((f"Jun {q:%Y}", ins, pop, ins - pop))
    old = pd.DataFrame(old, columns=["June", "Insured aged 65+ (%)", "Population aged 65+ (%)",
                                     "Gap (points)"]).set_index("June")
    lines += ["### Question 2: share aged 65 and over, insured pool against Australia", ""]
    lines += table(old, "June") + [""]

    cover = []
    for q in (pd.Timestamp(2007, 6, 30), pd.Timestamp(2025, 6, 30)):
        ins = a[a.quarter_end == q].groupby("age_band_start").insured_persons.sum()
        pop = p[p.quarter_end == q].groupby("age_band_start").population.sum()
        cover.append((100 * ins / pop).rename(f"Coverage {q:%Y} (%)"))
    cover = pd.concat(cover, axis=1)
    cover["Change (points)"] = cover.iloc[:, 1] - cover.iloc[:, 0]
    cover.index = [f"{i}-{i + 4}" if i < 95 else "95+" for i in cover.index]
    lines += ["### Question 2: hospital coverage by age band, June 2007 and June 2025", ""]
    lines += table(cover, "Age") + [""]

    head = OUT.read_text().split(MARKER)[0] if OUT.exists() and MARKER in OUT.read_text() \
        else "# Series breaks\n\n"
    OUT.write_text(head + MARKER + "\n\n" + "\n".join(lines))
    print(f"\nWrote the evidence into {OUT.relative_to(ROOT)}")
    explained = sum(e != "not explained in APRA's notes" for *_, e in jumps)
    print(f"Jumps found: {len(jumps)}, of which {explained} explained by APRA's notes")


if __name__ == "__main__":
    main()
