"""
Fail if a number in the README or docs was typed rather than generated.

    .venv/bin/python etl/check_docs.py

Every figure-like number in README.md and docs/*.md (a percentage, a count with thousands
separators, a number of points or of millions) must be one of the display strings in
data/findings.json or a row count in data/last_load.json. The README must carry every findings
block, and each block must equal what etl/findings.py renders from the data now, so the README
cannot drift from the figures. Exit code 1 on any failure, so the workflow stops.

Skipped, and why:
  code fences            commands and log lines, not prose
  generated regions      the findings blocks, breaks.py's table, and the files written whole by
                         scripts: findings.md, reconciliation.md, change-log.md
  docs/prior-work.md     quotes figures published by the ACCC, CHOICE and others, each with a
                         link; none of them is this project's
A short allowlist covers parameters and product facts, each with its reason.
"""

from __future__ import annotations

import json
import re
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))
import findings  # noqa: E402

ROOT = findings.ROOT
SKIP = {"findings.md", "reconciliation.md", "change-log.md", "prior-work.md"}
ALLOWED = {
    "0.05%": "the totals tolerance in etl/checks.py, a parameter",
    "100%": "the upper bound of the range check in etl/checks.py",
    "100,000": "Azure's free offer, vCore-seconds a month: a product fact",
}
TOKEN = re.compile(r"(?<![\w.])(?:[-+−]?\d{1,3}(?:,\d{3})+(?:\.\d+)?"
                   r"|[-+−]?\d+(?:\.\d+)?\s?%"
                   r"|[-+−]?\d+(?:\.\d+)?(?:\s|-)?(?:points?|pts|million))(?![\w%])")


def norm(token: str) -> str:
    t = token.replace("−", "-").replace("pts", "points")
    t = re.sub(r"(\d)(?:\s|-)?points?\b", r"\1 points", t)
    t = re.sub(r"(\d)\s?%", r"\1%", t)
    t = re.sub(r"(\d)\s?million", r"\1 million", t)
    return t.lstrip("+-")


def allowed_tokens() -> set[str]:
    data = json.loads((ROOT / "data" / "findings.json").read_text(encoding="utf-8"))
    load = json.loads((ROOT / "data" / "last_load.json").read_text(encoding="utf-8"))
    out = {norm(t) for t in ALLOWED}
    sources = [f["display"] for f in data["figures"]]
    sources += [str(v) for rows in data["tables"].values() for r in rows for v in r.values()]
    sources += [f"{n:,}" for n in load["rows"].values()]
    for s in sources:
        for m in TOKEN.finditer(s):
            out.add(norm(m.group(0)))
    return out


def prose(path: Path) -> str:
    text = path.read_text(encoding="utf-8")
    text = text.split("<!-- Generated by etl/breaks.py")[0]
    text = re.sub(r"```.*?```", "", text, flags=re.DOTALL)
    text = re.sub(r"<!-- findings:(\w+) -->.*?<!-- /findings:\1 -->", "", text, flags=re.DOTALL)
    return text


def main() -> None:
    allowed = allowed_tokens()
    failures: list[str] = []
    checked = 0
    for path in [ROOT / "README.md", *sorted((ROOT / "docs").glob("*.md"))]:
        if path.name in SKIP:
            continue
        for n, line in enumerate(prose(path).splitlines(), 1):
            for m in TOKEN.finditer(line):
                checked += 1
                if norm(m.group(0)) not in allowed:
                    failures.append(f"{path.relative_to(ROOT)}:{n}: {m.group(0)!r} is not in findings.json")

    readme = (ROOT / "README.md").read_text(encoding="utf-8")
    f, release = findings.build()
    for name, body in findings.blocks(f, release).items():
        m = re.search(rf"<!-- findings:{name} -->\n(.*?)\n<!-- /findings:{name} -->", readme, re.DOTALL)
        if not m:
            failures.append(f"README.md: the findings:{name} block is missing")
        elif m.group(1) != body:
            failures.append(f"README.md: the findings:{name} block is stale; run etl/findings.py")

    if failures:
        print("\n".join(failures))
        sys.exit(f"docs check failed: {len(failures)} problem(s)")
    print(f"docs check passed: {checked} numbers in the README and docs all come from findings.json, "
          f"and every README block is current")


if __name__ == "__main__":
    main()
